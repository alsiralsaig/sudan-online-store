import assert from 'node:assert/strict';
import { adminRevision, merchantCodeHash, merchantCodeMatches, newMerchantCode, passwordMatches, sessionRevisionMatches, signSession, validSigningSecret, verifySession } from '../src/server/securitySessions.ts';

const secret = 'integration-test-secret-not-a-production-secret';
const now = 1_800_000_000_000;
const code = newMerchantCode();
const hash = merchantCodeHash(code);
assert(hash);
assert(merchantCodeMatches(code, hash));
assert(merchantCodeMatches(code.toLowerCase().replace(/-/g, ' '), hash));
assert(!merchantCodeMatches('SND-1234-5678', hash));
assert.notEqual(merchantCodeHash(newMerchantCode()), hash);
assert(passwordMatches('example password', 'example password'));
assert(!passwordMatches('example password', 'other password'));
assert(!validSigningSecret('short'));
const merchant = signSession({ role: 'merchant', tenantId: 'tenant-one', revision: hash }, secret, now);
const claims = verifySession(merchant, secret, 'merchant', now + 1);
assert(claims);
assert.equal(claims.tenantId, 'tenant-one');
assert(sessionRevisionMatches(claims, hash));
assert(!sessionRevisionMatches(claims, merchantCodeHash(newMerchantCode())));
assert.equal(verifySession(merchant, secret, 'admin', now + 1), null);
assert.equal(verifySession(merchant, 'incorrect-signing-secret-that-is-long-enough', 'merchant', now + 1), null);
assert.equal(verifySession(merchant + 'x', secret, 'merchant', now + 1), null);
assert.equal(verifySession(merchant, secret, 'merchant', now + 14 * 24 * 60 * 60 * 1000), null);
const admin = signSession({ role: 'admin', revision: adminRevision('admin password') }, secret, now);
const adminClaims = verifySession(admin, secret, 'admin', now + 1);
assert(adminClaims && sessionRevisionMatches(adminClaims, adminRevision('admin password')));
assert(!sessionRevisionMatches(adminClaims!, adminRevision('changed password')));
assert.equal(verifySession(admin, secret, 'admin', now + 12 * 60 * 60 * 1000), null);
assert.throws(() => signSession({ role: 'admin', revision: adminRevision('x') }, 'short', now));
console.log('PASS: code entropy/format, signatures, role separation, expiry and credential rotation');
