/** يضيف وحدة كتبها المستخدم لقائمة الاختيار دون تكرار. */
export function mergeUnit(list: string[], value: string): string[] {
  const v = value.trim();
  if (!v || list.includes(v)) return list;
  return [...list, v];
}
