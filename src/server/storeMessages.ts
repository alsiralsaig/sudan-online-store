/**
 * رسائل المتاجر الجديدة — رسالتان منفصلتان تماماً:
 *   1) رسالة الكود: الكود لوحده فقط (سطر واحد) حتى يُنسخ نسخاً صحيحاً.
 *   2) رسالة الترحيب: تعريف مختصر + طريقة وضع الكود خطوة بخطوة.
 *
 * لماذا الفصل: الكود عندما يكون وسط كلام يُنسخ معه نص أو مسافات فيُرفض،
 * وكان التاجر يحتاج قراءة تعليمات طويلة ليجد الكود.
 *
 * قاعدة عامة: «متجري» — أي كود يُرسله التاجر يُفعّل متجره ويدخله في نفس
 * الطلب. لا انتظار تفعيل ولا خطوة ثانية، حتى لو كان المتجر جديداً.
 */

export interface StoreMessageInput {
  /** كود دخول المتجر بصيغته المعروضة SND-XXXX-XXXX-XXXX */
  code: string;
  storeName?: string;
  /** رابط تطبيق التاجر (يُستخدم في رسالة الترحيب فقط) */
  appLink?: string;
}

/** رابط تطبيق التاجر — يُستخدم في رسالة الترحيب فقط. */
export const MERCHANT_APP_LINK = 'https://sudan-online-store-eta.vercel.app/install.html';

/** رسالة الكود لوحده — بلا أي كلمة إضافية. */
export function codeOnlyMessage(code: string): string {
  return String(code || '').trim().toUpperCase();
}

/** رسالة الترحيب والتعريف — لا تحتوي الكود (يُرسل في رسالة مستقلة). */
export function welcomeMessage(input: StoreMessageInput): string {
  const name = String(input.storeName || 'متجرك').trim();
  const app = input.appLink || MERCHANT_APP_LINK;
  return [
    `مرحباً بك في سند 🌿`,
    `تم تفعيل متجر «${name}» على منصة سند، ومن اليوم تدير بيعه ومخزونه وكاشيره من مكان واحد.`,
    ``,
    `طريقة الدخول (مرة واحدة فقط):`,
    `١) افتح تطبيق التاجر: ${app}`,
    `٢) في خانة «دخول المتجر» اكتب كود متجرك — وصلك في رسالة منفصلة، انسخها كما هي والصقها.`,
    `٣) اضغط «دخول المتجر» — يدخلك متجرك مباشرة، ولا يظهر لك أي متجر آخر.`,
    ``,
    `ملاحظات:`,
    `• الكود واحد فقط لمتجرك، احفظه في مكان آمن ولا تشاركه.`,
    `• لا تكتبه بيدك: انسخ الرسالة التي بها الكود فقط لتفادي الخطأ.`,
    `• أول موظف (المالك) جاهز برمز سري 1234، ويمكنك إضافة بقية الموظفين من داخل التطبيق.`,
    `• لأي مساعدة تواصل معنا عبر واتساب من داخل التطبيق.`,
  ].join('\n');
}

/** واتساب: نص جاهز للرسالتين (كل واحدة برابط مستقل). */
export function whatsappLink(text: string, phone?: string): string {
  const base = phone ? `https://wa.me/${String(phone).replace(/[^0-9]/g, '')}` : 'https://wa.me/';
  return `${base}?text=${encodeURIComponent(text)}`;
}
